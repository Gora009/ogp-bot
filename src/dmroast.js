const pick = (list) => list[Math.floor(Math.random() * list.length)];
const COOLDOWN_MS = 20_000;
const WINDOW_MS = 10 * 60_000;

export const dmRoastEnabled = () => process.env.DM_ROAST === '1';

export function installDmRoast(client) {
  if (!dmRoastEnabled()) return;
  const seen = new Map(); // user → { last, times: [ts…] }
  client.on('messageCreate', async (m) => {
    if (m.author.bot || m.guildId) return;
    const now = Date.now();
    const s = seen.get(m.author.id) ?? { last: 0, times: [] };
    s.times = [...s.times.filter((t) => now - t < WINDOW_MS), now];
    seen.set(m.author.id, s);
    if (now - s.last < COOLDOWN_MS) return;
    s.last = now;

    const text = (m.content ?? '').toLowerCase();
    const list = /терпил/.test(text) ? TERPILA
      : /(^|[^а-яё])нет([^а-яё]|$)/.test(text) ? NET
        : m.stickers.size ? STICKER
          : m.attachments.size ? MEDIA
          : s.times.length >= 4 ? AGAIN
            : GENERIC;
    await m.reply({ content: pick(list), allowedMentions: { repliedUser: false } }).catch(() => {});
  });
  // память о людях — не дольше окна, чтобы не копилась
  setInterval(() => {
    const now = Date.now();
    for (const [id, s] of seen) if (now - s.last > WINDOW_MS) seen.delete(id);
  }, WINDOW_MS).unref();
}
